//! Gradle sync: a Groovy init script that writes the project model as JSON.
//!
//! The script is run with the project's own Gradle (wrapper or PATH). It only reads
//! the configured model (projects, applied plugins, tasks, source sets) once all
//! projects are evaluated, and only for the root build, so `buildSrc` and included
//! builds that also receive the init script do not overwrite the result.

use crate::GradleBuild;
use archipel_ide_runner::{RunnerError, TaskKind, TaskPlan};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Directory (relative to the project root) holding the init script and model cache.
pub const STATE_DIR: &str = ".archipel/gradle";
pub const INIT_SCRIPT: &str = "archipel-model.init.gradle";
pub const MODEL_FILE: &str = "model.json";
/// Task registered by the init script; requesting it is what triggers the export.
pub const MODEL_TASK: &str = "archipelModel";
/// JavaExec task registered by the init script; runs `-Parchipel.mainClass=<class>`.
pub const RUN_MAIN_TASK: &str = "archipelRunMain";

pub const INIT_SCRIPT_SOURCE: &str = r#"// Generated by Archipel IDE. Exports the Gradle project model for the IDE.
import groovy.json.JsonOutput

def archipelModelFile = gradle.startParameter.projectProperties.get('archipel.modelFile')

gradle.rootProject { root ->
    if (root.gradle.parent != null) return
    root.tasks.register('archipelModel') {
        description = 'Writes the Archipel IDE project model.'
    }
}

// Runs any main class of a JVM project (gutter run icons): -Parchipel.mainClass=...
gradle.allprojects { p ->
    if (p.gradle.parent != null) return
    p.plugins.withId('java') {
        p.tasks.register('archipelRunMain', JavaExec) {
            description = 'Runs the main class selected in Archipel IDE.'
            def selected = p.findProperty('archipel.mainClass')
            if (selected != null) {
                mainClass.set(selected.toString())
            }
            classpath = p.extensions.getByName('sourceSets').getByName('main').runtimeClasspath
            standardInput = System.in
        }
    }
}

gradle.projectsEvaluated { g ->
    if (g.parent != null || archipelModelFile == null) return
    def root = g.rootProject
    def projects = root.allprojects.collect { p ->
        def sourceSets = []
        def container = p.extensions.findByName('sourceSets')
        if (container != null) {
            container.each { s ->
                sourceSets << [
                    name: s.name,
                    java: s.java.srcDirs.collect { it.absolutePath },
                    resources: s.resources.srcDirs.collect { it.absolutePath },
                ]
            }
        }
        def libraries = []
        def runtime = p.configurations.findByName('runtimeClasspath')
        if (runtime != null && runtime.canBeResolved) {
            try {
                runtime.resolvedConfiguration.lenientConfiguration.artifacts.each { a ->
                    def id = a.moduleVersion.id
                    libraries << [name: "${id.group}:${id.name}:${id.version}".toString(), path: a.file.absolutePath]
                }
            } catch (Exception ignored) {
                // Unresolvable dependencies are left out of External Libraries.
            }
        }
        def tasks = p.tasks.findAll { !it.name.startsWith('archipel') }.collect { t ->
            [name: t.name, path: t.path, group: t.group?.toString(), description: t.description?.toString()]
        }
        [
            path: p.path,
            name: p.name,
            dir: p.projectDir.absolutePath,
            buildFile: p.buildFile.absolutePath,
            description: p.description?.toString(),
            plugins: [
                java: p.plugins.hasPlugin('java'),
                application: p.plugins.hasPlugin('application'),
                androidApplication: p.plugins.hasPlugin('com.android.application'),
                androidLibrary: p.plugins.hasPlugin('com.android.library'),
            ],
            tasks: tasks,
            sourceSets: sourceSets,
            libraries: libraries,
        ]
    }
    def out = new File(archipelModelFile)
    out.parentFile.mkdirs()
    out.text = JsonOutput.toJson([
        gradleVersion: g.gradleVersion,
        rootDir: root.rootDir.absolutePath,
        jdk: [home: System.getProperty('java.home'), version: System.getProperty('java.version')],
        projects: projects,
    ])
}
"#;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GradleModel {
    pub gradle_version: String,
    pub root_dir: PathBuf,
    /// The JVM that ran Gradle (External Libraries shows it as the project JDK).
    #[serde(default)]
    pub jdk: Option<JdkModel>,
    pub projects: Vec<ProjectModel>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct JdkModel {
    pub home: PathBuf,
    pub version: String,
}

/// A resolved runtime dependency (one jar).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LibraryModel {
    /// `group:name:version`.
    pub name: String,
    pub path: PathBuf,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectModel {
    pub path: String,
    pub name: String,
    pub dir: PathBuf,
    #[serde(default)]
    pub build_file: Option<PathBuf>,
    #[serde(default)]
    pub description: Option<String>,
    #[serde(default)]
    pub plugins: PluginModel,
    #[serde(default)]
    pub tasks: Vec<TaskModel>,
    #[serde(default)]
    pub source_sets: Vec<SourceSetModel>,
    #[serde(default)]
    pub libraries: Vec<LibraryModel>,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct PluginModel {
    pub java: bool,
    pub application: bool,
    pub android_application: bool,
    pub android_library: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TaskModel {
    pub name: String,
    pub path: String,
    #[serde(default)]
    pub group: Option<String>,
    #[serde(default)]
    pub description: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SourceSetModel {
    pub name: String,
    #[serde(default)]
    pub java: Vec<PathBuf>,
    #[serde(default)]
    pub resources: Vec<PathBuf>,
}

/// Group shown for tasks without a `group`, as in the reference tool window.
pub const OTHER_GROUP: &str = "other";

impl ProjectModel {
    /// Tasks grouped by lower-cased `group` (sorted), ungrouped ones under [`OTHER_GROUP`].
    pub fn task_groups(&self) -> BTreeMap<String, Vec<&TaskModel>> {
        let mut groups: BTreeMap<String, Vec<&TaskModel>> = BTreeMap::new();
        for task in &self.tasks {
            let group = task
                .group
                .as_deref()
                .filter(|group| !group.trim().is_empty())
                .unwrap_or(OTHER_GROUP)
                // The reference tool window lists groups in lower case.
                .to_lowercase();
            groups.entry(group).or_default().push(task);
        }
        for tasks in groups.values_mut() {
            tasks.sort_by(|a, b| a.name.cmp(&b.name));
        }
        groups
    }

    /// Direct sub-projects of this project in `model`.
    pub fn children<'a>(&self, model: &'a GradleModel) -> Vec<&'a ProjectModel> {
        model
            .projects
            .iter()
            .filter(|candidate| parent_path(&candidate.path).as_deref() == Some(&self.path))
            .collect()
    }
}

/// `:a:b` → `:a`, `:a` → `:`, `:` → none.
pub fn parent_path(path: &str) -> Option<String> {
    if path == ":" {
        return None;
    }
    match path.rsplit_once(':') {
        Some(("", _)) => Some(":".into()),
        Some((parent, _)) => Some(parent.into()),
        None => None,
    }
}

impl GradleModel {
    pub fn parse(json: &str) -> Result<Self, String> {
        serde_json::from_str(json).map_err(|error| format!("invalid Gradle model: {error}"))
    }

    pub fn root(&self) -> Option<&ProjectModel> {
        self.projects.iter().find(|project| project.path == ":")
    }

    pub fn project(&self, path: &str) -> Option<&ProjectModel> {
        self.projects.iter().find(|project| project.path == path)
    }

    pub fn task_count(&self) -> usize {
        self.projects
            .iter()
            .map(|project| project.tasks.len())
            .sum()
    }

    /// Finds a task by its full path (`:app:run`) or, for the root project, its name.
    pub fn task(&self, path: &str) -> Option<&TaskModel> {
        self.projects
            .iter()
            .flat_map(|project| &project.tasks)
            .find(|task| {
                task.path == path || (task.name == path && task.path == format!(":{path}"))
            })
    }

    /// Loads the model cached by the last successful sync.
    pub fn load_cached(root: &Path) -> Option<Result<Self, String>> {
        let text =
            std::fs::read_to_string(archipel_ide_compat::project_read_path(model_path(root)))
                .ok()?;
        Some(Self::parse(&text))
    }
}

pub fn model_path(root: &Path) -> PathBuf {
    root.join(STATE_DIR).join(MODEL_FILE)
}

impl GradleBuild {
    /// Writes the init script and returns the plan that syncs the model.
    ///
    /// The configuration cache is disabled for this invocation because the export
    /// reads the mutable project model.
    /// Writes (or refreshes) the Archipel IDE init script and returns its path.
    pub fn init_script(&self) -> Result<PathBuf, RunnerError> {
        // The first write in a project from before the rename copies `.jetthing/` to `.archipel/`.
        let dir = archipel_ide_compat::project_write_path(self.root.join(STATE_DIR));
        std::fs::create_dir_all(&dir)?;
        let script = dir.join(INIT_SCRIPT);
        if std::fs::read_to_string(&script).ok().as_deref() != Some(INIT_SCRIPT_SOURCE) {
            std::fs::write(&script, INIT_SCRIPT_SOURCE)?;
        }
        Ok(script)
    }

    pub fn sync_plan(&self) -> Result<TaskPlan, RunnerError> {
        let script = self.init_script()?;
        let model = model_path(&self.root);
        let _ = std::fs::remove_file(&model);
        let args = [
            "--init-script".to_owned(),
            script.display().to_string(),
            format!("-Parchipel.modelFile={}", model.display()),
            "-Dorg.gradle.configuration-cache=false".to_owned(),
            "--console=plain".to_owned(),
            MODEL_TASK.to_owned(),
        ];
        Ok(self.plan("Gradle Sync", args)?.with_kind(TaskKind::Sync))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"{
        "gradleVersion": "8.14.3",
        "rootDir": "/w/demo",
        "projects": [
            {"path": ":", "name": "demo", "dir": "/w/demo", "buildFile": "/w/demo/build.gradle.kts",
             "plugins": {"java": false},
             "tasks": [
                {"name": "help", "path": ":help", "group": "help", "description": "Displays a help message."},
                {"name": "wrapper", "path": ":wrapper", "group": "Build Setup"},
                {"name": "prepareKotlinBuildScriptModel", "path": ":prepareKotlinBuildScriptModel"}
             ]},
            {"path": ":app", "name": "app", "dir": "/w/demo/app",
             "plugins": {"java": true, "application": true},
             "tasks": [
                {"name": "run", "path": ":app:run", "group": "application"},
                {"name": "test", "path": ":app:test", "group": "verification"},
                {"name": "check", "path": ":app:check", "group": "verification"}
             ],
             "sourceSets": [{"name": "main", "java": ["/w/demo/app/src/main/java"], "resources": []}]},
            {"path": ":lib:core", "name": "core", "dir": "/w/demo/lib/core"}
        ]
    }"#;

    #[test]
    fn parses_model_and_groups_tasks() {
        let model = GradleModel::parse(SAMPLE).unwrap();
        assert_eq!(model.gradle_version, "8.14.3");
        assert_eq!(model.task_count(), 6);
        let app = model.project(":app").unwrap();
        assert!(app.plugins.application);
        let groups = app.task_groups();
        assert_eq!(
            groups["verification"]
                .iter()
                .map(|task| task.name.as_str())
                .collect::<Vec<_>>(),
            ["check", "test"]
        );
        let root = model.root().unwrap();
        assert_eq!(root.task_groups()["build setup"][0].name, "wrapper");
        assert_eq!(
            root.task_groups()[OTHER_GROUP][0].name,
            "prepareKotlinBuildScriptModel"
        );
        assert_eq!(
            model.task(":app:run").unwrap().group.as_deref(),
            Some("application")
        );
        assert_eq!(model.task("help").unwrap().path, ":help");
        assert!(model.task("run").is_none());
    }

    #[test]
    fn sub_project_hierarchy() {
        let model = GradleModel::parse(SAMPLE).unwrap();
        assert_eq!(parent_path(":lib:core").as_deref(), Some(":lib"));
        assert_eq!(parent_path(":app").as_deref(), Some(":"));
        assert_eq!(parent_path(":"), None);
        let children: Vec<_> = model
            .root()
            .unwrap()
            .children(&model)
            .iter()
            .map(|project| project.path.as_str())
            .collect();
        assert_eq!(children, [":app"]);
    }

    #[test]
    fn rejects_malformed_model() {
        assert!(
            GradleModel::parse("{}")
                .unwrap_err()
                .contains("invalid Gradle model")
        );
    }
}
