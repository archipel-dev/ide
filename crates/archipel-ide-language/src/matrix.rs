//! The language feature matrix (`docs/analysis/language-features.md`): which
//! generic structural features each language gets from its query files and
//! data row. Generated, and kept current by a test (`tests/feature_matrix.rs`).

use crate::queryset::{self, QueryKind};
use crate::registry::{LANGUAGES, LanguageSpec};
use crate::syntax_data::{StatementStyle, language_data};
use std::fmt::Write as _;

/// Number of patterns of a query (0 when absent).
fn patterns(spec: &'static LanguageSpec, kind: QueryKind) -> usize {
    queryset::query(spec, kind).map_or(0, |query| query.pattern_count())
}

fn cell(count: usize) -> String {
    if count == 0 {
        "-".into()
    } else {
        format!("{count}")
    }
}

/// Languages that appear in the matrix (inline Markdown is part of Markdown).
fn listed() -> impl Iterator<Item = &'static LanguageSpec> {
    LANGUAGES.iter().filter(|spec| spec.id != "markdown_inline")
}

/// The generated document. `golden(lang, feature)` says whether a golden test
/// file exists, which is what the last column reports.
pub fn render(golden: &dyn Fn(&str, &str) -> bool) -> String {
    let mut out = String::new();
    out.push_str("# Language features (generated)\n\n");
    out.push_str(
        "<!-- Generated by `cargo test -p archipel-ide-language --test feature_matrix`; \
         run with `UPDATE_SNAPSHOTS=1` to refresh. Do not edit by hand. -->\n\n",
    );
    out.push_str(
        "Every grammar is tier G0 (syntax only) plus file-local resolution where `locals.scm` exists (G1 data, \
         unlocked by the resolve package). Cells count the patterns of the language's query file; `-` means the \
         feature falls back to the generic grammar walk or is not meaningful for the language.\n\n",
    );
    out.push_str("## Structural queries\n\n");
    out.push_str(
        "| Language | Tier | folds | tags | brackets | indents | text objects | sticky | doc | locals |\n",
    );
    out.push_str("|---|---|---|---|---|---|---|---|---|---|\n");
    for spec in listed() {
        let _ = writeln!(
            out,
            "| {} (`{}`) | {:?} | {} | {} | {} | {} | {} | {} | {} | {} |",
            spec.name,
            spec.id,
            spec.tier,
            cell(patterns(spec, QueryKind::Folds)),
            cell(patterns(spec, QueryKind::Tags)),
            cell(patterns(spec, QueryKind::Brackets)),
            cell(patterns(spec, QueryKind::Indents)),
            cell(patterns(spec, QueryKind::TextObjects)),
            cell(patterns(spec, QueryKind::Sticky)),
            cell(patterns(spec, QueryKind::Doc)),
            cell(patterns(spec, QueryKind::Locals)),
        );
    }
    out.push_str("\n## Editing data and typed handlers\n\n");
    out.push_str("| Language | line comment | block comment | auto-pairs | quotes | statements | keywords |\n");
    out.push_str("|---|---|---|---|---|---|---|\n");
    for spec in listed() {
        let Some(data) = language_data(spec.id) else {
            continue;
        };
        let pairs: String = data
            .pairs
            .iter()
            .map(|(open, close)| format!("{open}{close}"))
            .collect::<Vec<_>>()
            .join(" ");
        let quotes: String = data.quotes.iter().collect();
        let statements = match data.statements {
            StatementStyle::None => "-".to_owned(),
            StatementStyle::Braces { semicolon: true } => "braces, `;`".to_owned(),
            StatementStyle::Braces { semicolon: false } => "braces".to_owned(),
            StatementStyle::Indent => "indent, `:`".to_owned(),
            StatementStyle::Shell => "then/do".to_owned(),
        };
        let block = data
            .block_comment
            .map(|(open, close)| {
                format!(
                    "`{open} {close}`{}",
                    if data.nested_block { " nested" } else { "" }
                )
            })
            .unwrap_or_else(|| "-".into());
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} | {}{} | {} |",
            spec.name,
            data.line_prefix()
                .map_or("-".to_owned(), |p| format!("`{p}`")),
            block,
            if pairs.is_empty() {
                "-".into()
            } else {
                format!("`{pairs}`")
            },
            if quotes.is_empty() {
                "-".into()
            } else {
                format!("`{quotes}`")
            },
            statements,
            if data.triple_quotes {
                ", triple quotes"
            } else {
                ""
            },
            data.keywords.len(),
        );
    }
    out.push_str("\n## Features served by the services\n\n");
    out.push_str("| Feature | Source | Languages |\n|---|---|---|\n");
    let with = |kind: QueryKind| listed().filter(|s| patterns(s, kind) > 0).count();
    let total = listed().count();
    let rows: [(&str, &str, String); 14] = [
        (
            "Fold regions, collapse by default, region markers",
            "`folds.scm`, `#set! collapsed`, `@fold.marker`",
            format!("{}/{total}", with(QueryKind::Folds)),
        ),
        (
            "Structure, breadcrumbs, modifiers, details",
            "`tags.scm` (`@modifier`, `@detail`), `doc.scm` (`@doc.skip`)",
            format!("{}/{total}", with(QueryKind::Tags)),
        ),
        (
            "Matching brace, code block start/end, angle and tag pairs",
            "`brackets.scm`",
            format!("{}/{total}", with(QueryKind::Brackets)),
        ),
        (
            "Extend/shrink selection with list groups",
            "`textobjects.scm` (`@select.group`)",
            format!(
                "{}/{total} (+ the grammar walk for all)",
                with(QueryKind::TextObjects)
            ),
        ),
        (
            "Enter indentation, Auto-Indent Lines, re-indent on `}`",
            "`indents.scm`",
            format!("{}/{total}", with(QueryKind::Indents)),
        ),
        (
            "Sticky scopes",
            "`sticky.scm` + multi-line `tags.scm` definitions",
            format!("{total}/{total}"),
        ),
        (
            "Next/Previous Method",
            "`tags.scm` functions and methods",
            format!("{}/{total}", with(QueryKind::Tags)),
        ),
        (
            "Move Statement",
            "`@select.group` elements",
            format!("{}/{total}", with(QueryKind::TextObjects)),
        ),
        (
            "Complete Current Statement",
            "statement style in the data row",
            format!(
                "{}/{total}",
                listed()
                    .filter(|s| language_data(s.id)
                        .is_some_and(|d| d.statements != StatementStyle::None))
                    .count()
            ),
        ),
        (
            "Comment with Block Comment",
            "block comment in the data row",
            format!(
                "{}/{total}",
                listed()
                    .filter(|s| language_data(s.id).is_some_and(|d| d.block_comment.is_some()))
                    .count()
            ),
        ),
        (
            "Syntax-aware auto-pairs, overtype, wrap selection",
            "data row + syntax context",
            format!("{total}/{total}"),
        ),
        ("Auto-close markup tags", "`html`, `xml`", "2/2".to_owned()),
        (
            "File-local resolve data",
            "`locals.scm`",
            format!("{}/{total}", with(QueryKind::Locals)),
        ),
        (
            "Doc comment association",
            "`doc.scm`",
            format!("{}/{total}", with(QueryKind::Doc)),
        ),
    ];
    for (feature, source, count) in rows {
        let _ = writeln!(out, "| {feature} | {source} | {count} |");
    }
    out.push_str("\n## Golden tests\n\n");
    out.push_str(
        "`crates/archipel-ide-language/tests/golden/<lang>/<feature>.{src,expected}`; `x` marks a pair that has a golden file.\n\n",
    );
    let features = [
        "folds",
        "structure",
        "brackets",
        "selection",
        "indents",
        "sticky",
        "textobjects",
        "locals",
    ];
    let _ = write!(out, "| Language |");
    for feature in features {
        let _ = write!(out, " {feature} |");
    }
    out.push_str("\n|---|");
    for _ in features {
        out.push_str("---|");
    }
    out.push('\n');
    for spec in listed() {
        let _ = write!(out, "| `{}` |", spec.id);
        for feature in features {
            let _ = write!(
                out,
                " {} |",
                if golden(spec.id, feature) { "x" } else { "-" }
            );
        }
        out.push('\n');
    }
    out
}
